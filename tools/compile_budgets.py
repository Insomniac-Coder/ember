"""`[BLD-10]` — the compile-time budgets of `[BUD-2]` as a release gate.

Measures B1-B9 over `bench/bigpkg` (`[BUD-1]`, generated by `bench/bigpkg/generate.py`): each
figure the median of `--runs` runs after `--warmups` warm-up runs (15 and 3, `[BUD-2]`), published
with its spread, the interquartile range over the median (`[BUD-3b]`). A fixed calibration workload
is timed before and after: a run whose calibration moves more than 10 % is inconclusive, not failed,
and each time is normalised by the calibration against the reference machine's
(`bench/bigpkg/reference.json`, `[BUD-3a]`). A figure fails its gate above its budget, or more than
15 % above the recorded baseline (`bench/bigpkg/baseline.json`) even inside it (`[BUD-3]`); a gate
applies only to a figure whose spread is below 15 % (`[BUD-3b]`).

The release workflow (`.github/workflows/release.yml`) runs it on every release tag, and a release
is cut only when it passes.

    python tools/compile_budgets.py [--ember EXE] [--work DIR] [--runs N] [--warmups N]
        [--modules N] [--lines N] [--header-lines N] [--only B1,B3] [--budgets FILE]
        [--baseline FILE] [--write-baseline] [--write-reference] [--json FILE] [--list]

Exit status: 0 every gate passes; 1 a figure fails its gate; 2 the run is inconclusive.
"""
import argparse
import hashlib
import importlib.util
import json
import os
import shutil
import statistics
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BIGPKG = os.path.join(ROOT, "bench", "bigpkg")
# The compiler's names (`ember_branding`): its executable, its variables.
CLI = "ember"
CACHE_VAR = "EMBER_CACHE"
NO_COMPILE_CACHE_VAR = "EMBER_NO_COMPILE_CACHE"

# `[BUD-2]` — each operation and its budget: milliseconds, B9 megabytes.
BUDGETS = {
    "B1": ("`ember check` after a one-function-body edit", 250),
    "B2": ("`ember build --reload` after a one-function-body edit", 1000),
    "B3": ("`ember build` after a one-function-body edit, `debug`", 1500),
    "B4": ("`ember build` after a signature change in a leaf module", 2500),
    "B5": ("`ember build` after a change to a widely imported type", 8000),
    "B6": ("clean `debug` build, cold cache", 40000),
    "B7": ("clean `development` build", 90000),
    "B8": ("`.embind` regeneration for a Vulkan-sized header", 3000),
    "B9": ("compiler peak memory, clean build", 3 * 1024),
}
BASELINE_MARGIN = 0.15
CALIBRATION_MARGIN = 0.10


def load_generator():
    spec = importlib.util.spec_from_file_location("bigpkg_generate", os.path.join(BIGPKG, "generate.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def calibrate():
    """`[BUD-3a]` — a fixed workload that does not depend on the compiler: hashing 64 MB, the
    median of seven times after one to wake the processor."""
    block = bytes(range(256)) * 4096

    def once():
        start = time.perf_counter()
        digest = hashlib.blake2b()
        for _ in range(64):
            digest.update(block)
        digest.hexdigest()
        return (time.perf_counter() - start) * 1000

    once()
    return statistics.median(once() for _ in range(7))


class TimedOut(Exception):
    """A command that ran past its limit, ended with everything it started."""


def end_tree(process):
    if os.name == "nt":
        subprocess.run(["taskkill", "/T", "/F", "/PID", str(process.pid)], capture_output=True)
    else:
        import signal
        os.killpg(process.pid, signal.SIGKILL)


class Runner:
    def __init__(self, ember, work):
        self.ember = ember
        self.work = work
        # Each run's limit, in seconds: ten times its figure's budget, at least a minute.
        self.limit = 60.0

    def run(self, args, cwd, env=None):
        """Run the compiler; its wall time in milliseconds, keeping what it wrote on standard error
        (`self.stderr`). A failing command stops the measurement: a figure of a failed build is no
        figure. One that runs past `self.limit` is ended and raises `TimedOut`."""
        environment = dict(os.environ)
        environment.update(env or {})
        start = time.perf_counter()
        process = subprocess.Popen([self.ember, *args], cwd=cwd, env=environment, stdout=subprocess.PIPE,
                                   stderr=subprocess.PIPE, start_new_session=os.name != "nt")
        try:
            out, err = process.communicate(timeout=self.limit)
        except subprocess.TimeoutExpired:
            end_tree(process)
            process.communicate()
            raise TimedOut(f"`{CLI} {' '.join(args)}` ran past {self.limit:.0f} s")
        elapsed = (time.perf_counter() - start) * 1000
        self.stderr = err.decode(errors="replace")
        if process.returncode != 0:
            raise RuntimeError(f"`{CLI} {' '.join(args)}` failed in {cwd}:\n{out.decode(errors='replace')}{self.stderr}")
        return elapsed

    def peak_memory_mb(self):
        """B9 — the compiler's own peak memory, from its `--timings=json` report."""
        for line in self.stderr.splitlines():
            if line.startswith('{"'):
                peak = json.loads(line).get("peak_memory_mb")
                if peak is not None:
                    return peak
        raise RuntimeError("the compiler reported no peak memory (`--timings=json`)")


def fresh(path):
    shutil.rmtree(path, ignore_errors=True)
    os.makedirs(path, exist_ok=True)
    return path


def operations(runner, generator, size):
    """Each figure's setup and one measured run (given the run's number, so every edit is new)."""
    work = runner.work
    pkg = os.path.join(work, "pkg")
    reload_pkg = os.path.join(work, "pkg-reload")
    edits = {"body": 0, "signature": 0, "type": 0}

    def edited(kind):
        edits[kind] += 1
        return edits[kind]

    def setup_pkg():
        generator.generate(pkg, *size)
        runner.run(["build"], pkg)

    def setup_reload():
        generator.generate(reload_pkg, *size)
        with open(os.path.join(reload_pkg, "ember.toml"), "a", encoding="utf-8") as manifest:
            manifest.write('\n[build]\nreload = "all"\n')
        runner.run(["build"], reload_pkg)

    def edit_then(kind, args, directory=None):
        def measure(_):
            generator.edit(directory or pkg, kind, edited(kind), size[0], size[1])
            return runner.run(args, directory or pkg)
        return measure

    def clean(args, cold):
        def measure(n):
            target = fresh(os.path.join(work, "clean-target"))
            env = {NO_COMPILE_CACHE_VAR: "1"}
            if cold:
                env[CACHE_VAR] = fresh(os.path.join(work, f"cold-cache-{n}"))
            return runner.run([*args, "--out-dir", target], pkg, env)
        return measure

    def bind(_):
        return runner.run(["bind", os.path.join("src", "vkimpl.h"), "--emit-embind"], pkg)

    clean_build = clean(["build", "--timings=json"], cold=False)

    def peak(n):
        clean_build(n)
        return runner.peak_memory_mb()
    return {
        "B1": (setup_pkg, edit_then("body", ["check"])),
        "B2": (setup_reload, edit_then("body", ["build", "--reload"], reload_pkg)),
        "B3": (setup_pkg, edit_then("body", ["build"])),
        "B4": (setup_pkg, edit_then("signature", ["build"])),
        "B5": (setup_pkg, edit_then("type", ["build"])),
        "B6": (setup_pkg, clean(["build"], cold=True)),
        "B7": (setup_pkg, clean(["build", "--profile", "development"], cold=False)),
        "B8": (setup_pkg, bind),
        "B9": (setup_pkg, peak),
    }


def spread(samples):
    """`[BUD-3b]` — the interquartile range over the median."""
    if len(samples) < 4:
        return (max(samples) - min(samples)) / statistics.median(samples) if statistics.median(samples) else 0.0
    q1, _, q3 = statistics.quantiles(samples, n=4)
    median = statistics.median(samples)
    return (q3 - q1) / median if median else 0.0


def verdicts(figures, budgets, baseline, factor):
    """Each figure's verdict: `pass`, `fail` (with why) or `not gated` (too noisy, `[BUD-3b]`).
    A time is normalised by the calibration `factor`; memory is not."""
    out = {}
    for name, samples in figures.items():
        median = statistics.median(samples)
        normalised = median if name == "B9" else median * factor
        noise = spread(samples)
        budget = budgets[name][1]
        result = {"median": median, "normalised": normalised, "spread": noise, "budget": budget,
                  "baseline": baseline.get(name), "runs": len(samples)}
        reasons = []
        if normalised > budget:
            reasons.append(f"over its budget ({normalised:.0f} > {budget})")
        if baseline.get(name) is not None and normalised > baseline[name] * (1 + BASELINE_MARGIN):
            reasons.append(f"more than {BASELINE_MARGIN:.0%} above the baseline ({normalised:.0f} > {baseline[name]:.0f})")
        if noise >= BASELINE_MARGIN:
            result["verdict"] = "not gated"
            result["why"] = f"its spread is {noise:.0%}, not below {BASELINE_MARGIN:.0%} [BUD-3b]"
        elif reasons:
            result["verdict"] = "fail"
            result["why"] = "; ".join(reasons)
        else:
            result["verdict"] = "pass"
        out[name] = result
    return out


def read_json(path, default):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    exe = CLI + (".exe" if os.name == "nt" else "")
    parser.add_argument("--ember", default=shutil.which(CLI) or os.path.join(ROOT, "target", "release", exe))
    parser.add_argument("--work", default=os.path.join(ROOT, "build", "budgets"))
    parser.add_argument("--runs", type=int, default=15)
    parser.add_argument("--warmups", type=int, default=3)
    parser.add_argument("--modules", type=int, default=400)
    parser.add_argument("--lines", type=int, default=50000)
    parser.add_argument("--header-lines", type=int, default=20000)
    parser.add_argument("--only", default=",".join(BUDGETS))
    parser.add_argument("--budgets", help="a JSON object of budgets by figure, replacing [BUD-2]'s")
    parser.add_argument("--baseline", default=os.path.join(BIGPKG, "baseline.json"))
    parser.add_argument("--reference", default=os.path.join(BIGPKG, "reference.json"))
    parser.add_argument("--write-baseline", action="store_true")
    parser.add_argument("--write-reference", action="store_true")
    parser.add_argument("--json")
    parser.add_argument("--list", action="store_true", help="print each figure's operation and budget as JSON")
    args = parser.parse_args(argv)
    if args.list:
        print(json.dumps({name: {"operation": what, "budget": budget} for name, (what, budget) in BUDGETS.items()}))
        return 0

    budgets = dict(BUDGETS)
    for name, value in read_json(args.budgets, {}).items() if args.budgets else []:
        budgets[name] = (budgets[name][0], value)
    wanted = [name.strip() for name in args.only.split(",") if name.strip()]
    unknown = [name for name in wanted if name not in BUDGETS]
    if unknown:
        parser.error(f"unknown figure(s): {', '.join(unknown)}")
    generator = load_generator()
    runner = Runner(os.path.abspath(args.ember), os.path.abspath(fresh(args.work)))
    size = (args.modules, args.lines, args.header_lines)
    ops = operations(runner, generator, size)

    before = calibrate()
    figures = {}
    timed_out = {}
    for name in wanted:
        setup, measure = ops[name]
        try:
            # A setup build may take as long as a clean one; a run, ten times its budget.
            runner.limit = max(60.0, 10 * budgets["B6"][1] / 1000)
            setup()
            runner.limit = max(60.0, 10 * budgets["B6" if name == "B9" else name][1] / 1000)
            for n in range(args.warmups):
                measure(n)
            figures[name] = [measure(args.warmups + n) for n in range(args.runs)]
            print(f"{name}: measured", flush=True)
        except TimedOut as error:
            # A figure that does not finish is over its budget by ten times or more.
            figures[name] = [budgets[name][1] * 10]
            timed_out[name] = str(error)
            print(f"{name}: {error}", flush=True)
    after = calibrate()

    drift = abs(after - before) / before
    reference = read_json(args.reference, {})
    calibration = (before + after) / 2
    factor = reference["calibration_ms"] / calibration if reference.get("calibration_ms") else 1.0
    if args.write_reference:
        with open(args.reference, "w", encoding="utf-8", newline="\n") as f:
            json.dump({"calibration_ms": round(calibration, 3), "machine": machine()}, f, indent=2)
            f.write("\n")
    results = verdicts(figures, budgets, read_json(args.baseline, {}), factor)
    for name, why in timed_out.items():
        results[name].update({"verdict": "fail", "why": f"it did not finish: {why}", "timed_out": True})
    report = {"schema": 1, "machine": machine(), "calibration_ms": [before, after], "drift": drift,
              "factor": factor, "size": {"modules": size[0], "lines": size[1], "header_lines": size[2]},
              "figures": results}
    unit = {"B9": "MB"}
    print(f"calibration {before:.0f} ms then {after:.0f} ms (drift {drift:.1%}); "
          f"times normalised by {factor:.3f} to the reference machine")
    print(f"{'':4} {'median':>10} {'spread':>7} {'normalised':>11} {'budget':>8}  verdict")
    for name, result in results.items():
        u = unit.get(name, "ms")
        print(f"{name:4} {result['median']:>8.0f}{u:>2} {result['spread']:>7.1%} {result['normalised']:>9.0f}{u:>2} "
              f"{result['budget']:>6}{u:>2}  {result['verdict']}{': ' + result['why'] if 'why' in result else ''}"
              f"  ({BUDGETS[name][0]})")
    if args.json:
        with open(args.json, "w", encoding="utf-8", newline="\n") as f:
            json.dump(report, f, indent=2)
            f.write("\n")
    if drift > CALIBRATION_MARGIN:
        print(f"inconclusive: the calibration moved {drift:.1%}, more than {CALIBRATION_MARGIN:.0%} [BUD-3a]")
        return 2
    if args.write_baseline:
        with open(args.baseline, "w", encoding="utf-8", newline="\n") as f:
            json.dump({name: round(result["normalised"], 1) for name, result in results.items()}, f, indent=2)
            f.write("\n")
    failed = [name for name, result in results.items() if result["verdict"] == "fail"]
    if failed:
        print(f"release gate: FAILED ({', '.join(failed)}) [BLD-10]")
        return 1
    print("release gate: passed [BLD-10]")
    return 0


def machine():
    import platform
    return {"system": platform.system(), "machine": platform.machine(), "processor": platform.processor(),
            "cores": os.cpu_count()}


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
