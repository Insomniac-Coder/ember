"""The Unicode case-mapping tables of the runtime (`[TXT-10]`'s `to_upper` and
`to_lower`), generated from Python's own full case mappings, and the character
classes of `char`'s `is_alphabetic`, `is_digit` and `is_alphanumeric` (ODR-183),
as Python's `isalpha`, `isdigit` and `isnumeric` of one character give them.

Writes the section between the two markers in
`runtime/ember_rt/templates/ember_rt.c.in`, and the same class runs as
`compiler/ember_interp/src/char_classes.rs` for the evaluator, so a class is the same
at compile time and at run time (`[CT-4]`); `--check` fails when either is not what
this Python would write (the Unicode version is in their first lines).

    python tools/unicode_case.py            # rewrite the section
    python tools/unicode_case.py --check    # verify it
"""
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / 'runtime' / 'ember_rt' / 'templates' / 'ember_rt.c.in'
EVALUATOR = ROOT / 'compiler' / 'ember_interp' / 'src' / 'char_classes.rs'
BEGIN = '/* BEGIN GENERATED: tools/unicode_case.py */\n'
END = '/* END GENERATED: tools/unicode_case.py */\n'


def table(name, pick):
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        mapped = pick(chr(cp))
        if mapped != chr(cp):
            codes = [ord(c) for c in mapped] + [0, 0, 0]
            rows.append(f'    {{0x{cp:X}, {{0x{codes[0]:X}, 0x{codes[1]:X}, 0x{codes[2]:X}}}}},')
    return (f'static const ember_case_entry {name}[] = {{\n' + '\n'.join(rows) + '\n};\n'
            f'static const size_t {name}_len = sizeof {name} / sizeof {name}[0];\n')


def runs(test):
    """The runs of code points past ASCII for which `test` holds, as first and last pairs: the
    runtime asks the table only for those, ASCII being decided inline (`std.string`)."""
    found, first = [], None
    for cp in range(0x80, 0x110001):
        holds = cp <= 0x10FFFF and not 0xD800 <= cp <= 0xDFFF and test(chr(cp))
        if holds and first is None:
            first = cp
        elif not holds and first is not None:
            found.append((first, cp - 1))
            first = None
    return found


def ranges(name, test):
    rows = [f'    {{0x{first:X}, 0x{last:X}}},' for first, last in runs(test)]
    return (f'static const ember_char_range {name}[] = {{\n' + '\n'.join(rows) + '\n};\n'
            f'static const size_t {name}_len = sizeof {name} / sizeof {name}[0];\n')


CLASSES = [('ALPHABETIC', 'ember_alphabetic_ranges', str.isalpha), ('DIGIT', 'ember_digit_ranges', str.isdigit),
           ('NUMERIC', 'ember_numeric_ranges', str.isnumeric)]


def evaluator_file():
    """The evaluator's copy of the class runs: `ember_char_class`'s, in the order it numbers them."""
    out = ('//! Generated by tools/unicode_case.py: do not edit. The runs of characters past ASCII that\n'
           f'//! Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}) calls alphabetic, digits and numeric,\n'
           '//! the runtime\'s `ember_char_class` tables (ODR-183), so the evaluator classes a `char` as the\n'
           '//! compiled program does (`[CT-4]`).\n\n')
    for rust, _, test in CLASSES:
        rows = ''.join(f'    (0x{first:X}, 0x{last:X}),\n' for first, last in runs(test))
        out += f'pub(crate) static {rust}: &[(u32, u32)] = &[\n{rows}];\n\n'
    return out.rstrip('\n') + '\n'


def section():
    return (BEGIN
            + f'/* Unicode {unicodedata.unidata_version}: full case mappings, as Python {sys.version.split()[0]} gives them. */\n'
            + 'typedef struct ember_case_entry { uint32_t cp; uint32_t to[3]; } ember_case_entry;\n'
            + table('ember_upper_table', str.upper)
            + table('ember_lower_table', str.lower)
            + '/* ODR-183: the characters past ASCII Python calls alphabetic, digits and numeric. */\n'
            + 'typedef struct ember_char_range { uint32_t first; uint32_t last; } ember_char_range;\n'
            + ''.join(ranges(c_name, test) for _, c_name, test in CLASSES)
            + END)


def main():
    text = TEMPLATE.read_text(encoding='utf-8')
    start, end = text.index(BEGIN), text.index(END) + len(END)
    wanted = text[:start] + section() + text[end:]
    classes = evaluator_file()
    if '--check' in sys.argv:
        current = EVALUATOR.read_text(encoding='utf-8') if EVALUATOR.exists() else ''
        if wanted != text or classes != current:
            print('the case tables are stale: run python tools/unicode_case.py')
            sys.exit(1)
        print('case tables current')
        return
    TEMPLATE.write_text(wanted, encoding='utf-8', newline='\n')
    EVALUATOR.write_text(classes, encoding='utf-8', newline='\n')
    print('wrote the case tables')


if __name__ == '__main__':
    main()
