"""`[BUD-1]` — `bench/bigpkg`: the generated package the compile-time budgets (`[BUD-2]`) and the
reload budget (`[HR-1]`) are measured over. 50,000 lines in 400 modules, about 15 % of them generic
code, and one C header import of Vulkan's size (`vk_like.h`, generated beside it).

Each module `mods/mNNN.em` declares, in the program's ordinary shapes: a value struct with
methods, a class, an enum with payloads, plain functions with loops and branches, and its generic
share (a generic struct and generic functions, instantiated by the module that imports it). Modules
import a few earlier ones, so the package is a graph and not 400 islands. `main.em` holds a live
set of 10,000 class instances in a static, as `[BEN-8]` and `[HR-1]` measure over, and exports
`game_frame`, which a host calls once a frame: it moves every instance on and calls into the
modules, among them `mods/m200.em`'s `edit_me`, the one function body an edit changes.

usage: python bench/bigpkg/generate.py <out-dir> [--reload all|none]
The package is written to <out-dir> (the build of the repository keeps generated packages under
build/, which git ignores); its size is printed. The same arguments write the same files."""
import pathlib
import sys

MODULES = 400
LINES = 50_000
STRUCTS = 1_400
ENUMS = 600
FUNCTIONS = 1_600


def module(n):
    """One module's text: about 125 lines, about 15 % of them generic."""
    imports = sorted({k for k in (n - 1, n // 2, n - 7) if 0 <= k < n})
    lines = [f'## Module {n} of bench/bigpkg (generated by bench/bigpkg/generate.py; do not edit).', '']
    for k in imports:
        lines.append(f'from mods.m{k:03} import Vec{k}, mix{k}, Pair{k}, pair_sum{k}')
    lines += [
        '',
        '@derive(Copy)',
        f'pub struct Vec{n}:',
        '    pub x: f64 = 0.0',
        '    pub y: f64 = 0.0',
        '    pub z: f64 = 0.0',
        '',
        '    pub fn length_squared(self) -> f64:',
        '        return self.x * self.x + self.y * self.y + self.z * self.z',
        '',
        f'    pub fn plus(self, other: Vec{n}) -> Vec{n}:',
        f'        return Vec{n}(x = self.x + other.x, y = self.y + other.y, z = self.z + other.z)',
        '',
        f'    pub fn scaled(self, k: f64) -> Vec{n}:',
        f'        return Vec{n}(x = self.x * k, y = self.y * k, z = self.z * k)',
        '',
        f'pub class Body{n}:',
        f'    pub pos: Vec{n} = Vec{n}()',
        f'    pub vel: Vec{n} = Vec{n}(x = 1.0)',
        '    pub mass: f64 = 1.0',
        '    pub id: int = 0',
        '',
        '    pub fn step(mut self, dt: f64):',
        '        self.pos = self.pos.plus(self.vel.scaled(dt))',
        '        if self.pos.length_squared() > 1000000.0:',
        f'            self.pos = Vec{n}()',
        '',
        '    pub fn energy(self) -> f64:',
        '        return 0.5 * self.mass * self.vel.length_squared()',
        '',
        f'pub enum Kind{n}:',
        '    Empty',
        '    Count(int)',
        '    Point(f64, f64)',
        '',
        f'pub fn classify{n}(k: Kind{n}) -> int:',
        '    match k:',
        f'        Kind{n}.Empty:',
        '            return 0',
        f'        Kind{n}.Count(c):',
        '            return c',
        f'        Kind{n}.Point(a, b):',
        '            return (a + b) as int',
        '',
        f'pub fn mix{n}(a: int, b: int) -> int:',
        '    total = 0',
        '    for i in 0..8:',
        '        if (a + i) % 3 == 0:',
        '            total += b',
        '        else:',
        '            total += a % 7',
        '    return total',
        '',
        f'pub fn spread{n}(xs: Array[int]) -> int:',
        '    best = 0',
        '    for x in xs:',
        '        if x > best:',
        '            best = x',
        '    return best',
        '',
        f'pub fn walk{n}(count: int) -> int:',
        '    steps = 0',
        '    left = count',
        '    while left > 0:',
        '        left = left // 2 if left % 2 == 0 else left - 1',
        '        steps += 1',
        '    return steps',
        '',
        f'pub fn label{n}(v: int) -> String:',
        '    if v < 0:',
        '        return "negative"',
        '    if v == 0:',
        '        return "zero"',
        '    return f"positive {v}"',
    ]
    calls = ' + '.join(f'mix{k}({n}, {k})' for k in imports) or '0'
    lines += [
        '',
        f'pub fn reach{n}(seed: int) -> int:',
        f'    k = Kind{n}.Count(seed % 5)',
        f'    return classify{n}(k) + walk{n}(seed % 64) + {calls}',
        '',
        f'pub fn bodies{n}(count: int) -> Array[Body{n}]:',
        f'    out: Array[Body{n}] = []',
        '    for i in 0..count:',
        f'        b = Body{n}()',
        '        b.id = i',
        '        out.push(b)',
        '    return out',
        '',
        '# The generic share: a generic struct and generic functions over it, instantiated by the',
        '# modules that import this one.',
        f'pub struct Pair{n}[T]:',
        '    pub first: T',
        '    pub second: T',
        '',
        f'pub fn pair_sum{n}[T: Add[Output = T] + Copy](p: Pair{n}[T]) -> T:',
        '    return p.first + p.second',
        '',
        f'pub fn clamp{n}(x: int) -> int:',
        '    if x < 0:',
        '        return 0',
        '    return x',
        '',
        f'pub fn fold{n}[T: Add[Output = T] + Copy](xs: Array[T], start: T) -> T:',
        '    total = start',
        '    for x in xs:',
        '        total = total + x',
        '    return total',
        '',
        f'pub fn pair_swap{n}[T: Copy](p: Pair{n}[T]) -> Pair{n}[T]:',
        f'    return Pair{n}[T](first = p.second, second = p.first)',
        '',
        f'pub fn count_eq{n}[T: Eq + Copy](xs: Array[T], v: T) -> int:',
        '    found = 0',
        '    for x in xs:',
        '        if x == v:',
        '            found += 1',
        '    return found',
    ]
    uses = ' + '.join(f'pair_sum{k}(Pair{k}[int](first = {n}, second = {k}))' for k in imports) or '0'
    lines += [
        '',
        f'pub fn generic_use{n}() -> int:',
        f'    p = Pair{n}[int](first = {n}, second = 3)',
        f'    q = Pair{n}[f64](first = 1.5, second = 2.5)',
        f'    return pair_sum{n}(p) + clamp{n}(-3) + fold{n}([1, 2, 3], 0) + count_eq{n}([1, 2, 1], 1) + pair_swap{n}(p).first + pair_sum{n}(q) as int + {uses}',
    ]
    if n == 200:
        lines += ['', '## The function body the reload benchmark edits ([HR-1]).', 'pub fn edit_me(x: int) -> int:', '    return x + 1']
    if n == 7:
        lines += ['', '## The module that imports the C header of Vulkan\'s size ([BUD-1]).',
                  'import c "vk_like.h" as vk', '', 'pub fn vk_extent(e: vk.VkExtent2D) -> int:', '    return e.width as int + e.height as int']
    return lines


def header():
    """A C header of Vulkan's size: handles, enums, structs and function prototypes in its shapes."""
    lines = ['/* Generated by bench/bigpkg/generate.py ([BUD-1]): a C header of Vulkan\'s size. */',
             '#pragma once', '#include <stdint.h>', '#include <stddef.h>', '',
             'typedef uint32_t VkFlags;', 'typedef uint32_t VkBool32;', 'typedef uint64_t VkDeviceSize;',
             'typedef struct VkExtent2D { uint32_t width; uint32_t height; } VkExtent2D;', '']
    for n in range(200):
        lines.append(f'typedef struct VkHandle{n}_T* VkHandle{n};')
    lines.append('')
    for n in range(ENUMS):
        lines.append(f'typedef enum VkEnum{n} {{')
        for v in range(6):
            lines.append(f'    VK_ENUM{n}_VALUE{v} = {v * (n % 5 + 1)},')
        lines.append(f'    VK_ENUM{n}_MAX_ENUM = 0x7FFFFFFF')
        lines.append(f'}} VkEnum{n};')
    lines.append('')
    for n in range(STRUCTS):
        lines.append(f'typedef struct VkStruct{n} {{')
        lines.append(f'    VkEnum{n % ENUMS} sType;')
        lines.append('    const void* pNext;')
        lines.append(f'    VkFlags flags{n};')
        lines.append(f'    uint32_t count{n};')
        lines.append(f'    VkDeviceSize size{n};')
        lines.append(f'    float weights{n}[4];')
        lines.append(f'    VkHandle{n % 200} handle;')
        lines.append(f'}} VkStruct{n};')
    lines.append('')
    for n in range(FUNCTIONS):
        lines.append(f'int32_t vkCall{n}(VkHandle{n % 200} handle, const VkStruct{n % STRUCTS}* info, VkStruct{(n * 7) % STRUCTS}* out);')
    return lines


def main_module():
    """The root: 10,000 live instances in a static, and the export a host calls each frame."""
    lines = ['## The root of bench/bigpkg (generated by bench/bigpkg/generate.py; do not edit).',
             'from std.sync import Atomic, Mutex', 'from mods.m200 import edit_me']
    picks = [0, 57, 123, 200, 311, 399]
    for k in picks:
        lines.append(f'from mods.m{k:03} import reach{k}, generic_use{k}')
    lines += ['', '@sync', 'class Particle:', '    x: Atomic[int] = Atomic(0)', '    step: int = 1', '',
              'static WORLD: Mutex[Array[Particle]] = Mutex([])', '',
              '@export("game_frame")', 'extern "C" fn frame(turn: i64) -> i64:', '    with world = WORLD.lock():',
              '        if world.len() == 0:', '            for k in 0..10000:', '                world.push(Particle())',
              '        for p in world:', '            p.x.fetch_add(p.step)',
              '        return edit_me(0) * 100000 + world.len()', '',
              'fn touch() -> int:', '    return ' + ' + '.join(f'reach{k}(3) + generic_use{k}()' for k in picks), '',
              'fn main():', '    println(touch())']
    return lines


def main():
    args = sys.argv[1:]
    reload = 'all'
    if '--reload' in args:
        at = args.index('--reload')
        reload = args[at + 1]
        del args[at:at + 2]
    if len(args) != 1:
        sys.exit(__doc__)
    out = pathlib.Path(args[0])
    (out / 'mods').mkdir(parents=True, exist_ok=True)
    total = 0
    generic = 0
    for n in range(MODULES):
        lines = module(n)
        # A generic item's lines: from a header with type parameters to the blank line after it.
        inside = False
        for line in lines:
            inside = (inside and line != '') or (line.startswith(('pub fn ', 'pub struct ')) and '[T' in line.split('(')[0])
            generic += inside
        text = '\n'.join(lines) + '\n'
        total += text.count('\n')
        (out / 'mods' / f'm{n:03}.em').write_text(text, encoding='utf-8')
    root = '\n'.join(main_module()) + '\n'
    total += root.count('\n')
    (out / 'main.em').write_text(root, encoding='utf-8')
    head = '\n'.join(header()) + '\n'
    (out / 'mods' / 'vk_like.h').write_text(head, encoding='utf-8')
    (out / 'ember.toml').write_text(f'[package]\nname = "bigpkg"\n\n[build]\nreload = "{reload}"\n', encoding='utf-8')
    print(f'{out}: {MODULES} modules and main, {total} lines of Ember ({generic * 100 / total:.1f} % generic); vk_like.h {head.count(chr(10))} lines')


if __name__ == '__main__':
    main()
