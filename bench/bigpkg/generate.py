"""`bench/bigpkg` (`[BUD-1]`): the generated package the compile-time budgets of `[BLD-10]` are
measured over. By default 400 modules and 50,000 lines of Ember, 15 % of them generic code, and
one C header import of Vulkan's size; the same arguments always write the same bytes.

Module `m000` holds the types every other module imports (`Item`, the widely imported type that
`[BUD-2]`'s B5 changes). Module `mN` imports `m000` and up to two modules before it, so the
imports form a layered graph; the last module is a leaf, imported by `main` alone (B4 changes its
signature). Module `m001` imports C: `vkimpl.h`, a generated header of Vulkan's size, and
`vkimpl.c`, which defines the few functions it calls (`[FFI-6]`).

    python bench/bigpkg/generate.py <out-dir> [--modules N] [--lines N] [--header-lines N] [--live]

`edit(out, kind, n)` makes the edits the budgets time (`body`, `signature`, `type`), each one
new for each `n`, so no build cache ever serves the edited package. `--live` writes the reloadable
package of `[HR-1]`, whose `main` keeps running with 10,000 live instances (`live_main_module`).
"""
import argparse
import os
import sys

GENERIC_SHARE = 0.15
HEADER_LINES = 20000


def module_name(index):
    return f"m{index:03d}"


def imports(index):
    """The modules module `index` imports: `m000`, and up to two before it."""
    if index == 0:
        return []
    chosen = {0}
    for step in (1, 7):
        if index - step > 0:
            chosen.add(index - step)
    return sorted(chosen)


def core_module():
    """`m000`: the types every module imports."""
    return """# Generated by bench/bigpkg/generate.py. Do not edit.
# The types every module of the package imports (`[BUD-2]` B5 changes `Item`).

pub struct Item:
    pub key: int
    pub weight: int

pub enum Shape:
    Dot(x: int)
    Line(x: int, y: int)
    Nothing

pub fn item_score(it: Item) -> int:
    return it.key * 3 + it.weight

pub fn shape_size(s: Shape) -> int:
    match s:
        Dot(x):
            return x
        Line(x, y):
            return x + y
        Nothing:
            return 0

pub fn larger[T: Ord](a: T, b: T) -> T:
    if a > b:
        return a
    return b
"""


def plain_block(index, block):
    """About 20 lines of ordinary code: a struct, an enum match and a loop over a list."""
    n = f"{index}_{block}"
    return f"""pub struct S{n}:
    pub a: int
    pub b: int
    pub c: int

pub fn make_{n}(seed: int) -> S{n}:
    return S{n}(seed, seed * 2 + {block}, seed % 7)

pub fn fold_{n}(s: S{n}, rounds: int) -> int:
    total = 0
    values: Array[int] = []
    for i in 0..rounds:
        values.push(s.a * i + s.b - s.c)
    for v in values:
        if v % 3 == 0:
            total += v
        else:
            total -= v // 2
    return total + shape_size(Shape.Line(s.a, s.c))

"""


def generic_block(index, block):
    """About 20 lines of generic code: a generic struct, its methods and a bounded function."""
    n = f"{index}_{block}"
    return f"""pub struct Pair{n}[T: Copy]:
    pub first: T
    pub second: T

    pub fn swapped(self) -> Pair{n}[T]:
        return Pair{n}[T](self.second, self.first)

pub fn best_{n}[T: Ord + Copy](items: Array[T], start: T) -> T:
    best = start
    for x in items:
        best = larger(best, x)
    return best

pub fn pair_total_{n}(seed: int) -> int:
    p = Pair{n}[int](seed, seed + {block + 1})
    q = p.swapped()
    xs: Array[int] = [q.first, q.second, seed % 5]
    return best_{n}(xs, 0) + q.first

"""


def body_function(index, value):
    """The function `[BUD-2]`'s one-function-body edits change: its constant is `value`."""
    return f"""pub fn work_{index}(seed: int) -> int:
    acc = seed
    for i in 0..8:
        acc = (acc * 31 + i + {value}) % 1000003
    return acc

"""


def module_text(index, count, lines_per_module, body_value=1):
    head = [f"# Generated by bench/bigpkg/generate.py: module {index} of {count}. Do not edit."]
    head.append("from m000 import Item, Shape, item_score, shape_size, larger")
    head += [f"import {module_name(i)}" for i in imports(index) if i != 0]
    if index == 1:
        head.append('import c "./vkimpl.c"')
    text = "\n".join(head) + "\n\n" + body_function(index, body_value)
    parts = []
    used = text.count("\n")
    block = 0
    generic_lines = 0
    # Another block of about 20 lines while it, and the entry's line calling it, still fit with the
    # entry's own five lines.
    while used + 20 + len(parts) + 1 + 5 <= lines_per_module:
        generic = generic_lines < GENERIC_SHARE * max(used, 1)
        part = generic_block(index, block) if generic else plain_block(index, block)
        if generic:
            generic_lines += part.count("\n")
        parts.append((generic, block))
        text += part
        used += part.count("\n")
        block += 1
    # The module's entry: each block once, and its imports' entries.
    calls = []
    for generic, b in parts:
        n = f"{index}_{b}"
        calls.append(f"    total += pair_total_{n}(seed)" if generic else f"    total += fold_{n}(make_{n}(seed), 4)")
    for i in imports(index):
        if i != 0:
            calls.append(f"    total += {module_name(i)}.work_{i}(seed)")
    if index == 1:
        calls.append("    unsafe:  # SAFETY(ffi): a pure function of its arguments")
        calls.append("        total += c.vk_mix(seed, 3)")
    text += f"pub fn run_{index}(seed: int) -> int:\n    total = work_{index}(seed) + item_score(Item(seed, {index}))\n"
    text += "\n".join(calls) + "\n    return total\n"
    return text


def leaf_module(index, count, wide=False):
    """The leaf module: imported by `main` alone; B4 changes `leaf_value`'s signature."""
    ty = "i64" if wide else "int"
    return f"""# Generated by bench/bigpkg/generate.py: module {index} of {count}, the leaf. Do not edit.
from m000 import Item, item_score

pub fn leaf_value(x: {ty}) -> {ty}:
    return x * 2 + 1

pub fn run_{index}(seed: int) -> int:
    return item_score(Item(seed, {index}))
"""


def core_with_field(extra):
    """`m000` with `Item`'s last field present or not: B5's change to a widely imported type."""
    text = core_module()
    if extra:
        text = text.replace("    pub weight: int\n", f"    pub weight: int\n    pub tag: int = {extra}\n", 1)
    return text


def main_module(count, calls=None):
    """`main`: each module's entry called in turn, or with `calls` (`fanout_modules`) only those."""
    calls = calls if calls is not None else [(module_name(i), f"run_{i}") for i in range(1, count)]
    lines = ["# Generated by bench/bigpkg/generate.py. Do not edit."]
    lines += [f"import {module}" for module in dict.fromkeys([module for module, _ in calls] + [module_name(count - 1)])]
    lines += ["", "fn main():", "    total = 0"]
    for i, (module, function) in enumerate(calls, 1):
        lines.append(f"    total += {module}.{function}(total % 1000 + {i})")
    lines.append(f"    println(total, {module_name(count - 1)}.leaf_value(3))")
    return "\n".join(lines) + "\n"


def fanout_modules(count, fanout):
    """`--fanout N` (ODR-281): `main` reaches the modules' entries through a tree of modules each
    calling at most `N` entries (`t1_000` calls `m001`..`m064`'s, `t2_000` calls `t1_000`..`t1_063`'s,
    and so on), and calls at most `N` itself, so no module grows with the package: its biggest module
    is the same at every size, which a compiler holding only what the module it compiles needs shows
    as a flat peak. The tree's modules as (name, text), and `main`'s calls."""
    calls = [(module_name(i), f"run_{i}") for i in range(1, count)]
    modules = []
    level = 0
    while len(calls) > fanout:
        level += 1
        above = []
        for k in range(0, len(calls), fanout):
            name = f"t{level}_{k // fanout:03d}"
            group = calls[k:k + fanout]
            lines = [f"# Generated by bench/bigpkg/generate.py: a module of the call tree (--fanout {fanout}). Do not edit."]
            lines += [f"import {module}" for module in dict.fromkeys(module for module, _ in group)]
            lines += ["", f"pub fn run_{name}(seed: int) -> int:", "    total = seed"]
            for i, (module, function) in enumerate(group, 1):
                lines.append(f"    total += {module}.{function}(total % 1000 + {i})")
            lines.append("    return total")
            modules.append((name, "\n".join(lines) + "\n"))
            above.append((name, f"run_{name}"))
        calls = above
    return modules, calls


LIVE_INSTANCES = 10000


def live_main_module(count):
    """`[HR-1]`'s `main`: the package's program kept running, as a game is, with `[BEN-8]`'s live set
    of 10,000 instances, each moved on by every frame. A frame prints what the middle module's
    `work` (the function the `body` edit changes) gives whenever it changes, with how many instances
    are still there, then reaches `std.hot.checkpoint()`, where a reload applies, and sleeps a
    millisecond. It ends itself after ten minutes."""
    middle = count // 2
    lines = ["# Generated by bench/bigpkg/generate.py. Do not edit.",
             "# [HR-1]'s live program: 10,000 instances, and the edited function's value each time it changes.",
             "import std.hot", "from std.time import Duration, Instant, sleep"]
    lines += [f"import {module_name(i)}" for i in range(1, count)]
    lines += ["", "class Particle:", "    x: int = 0", "    step: int = 1", "", "fn main():", "    total = 0"]
    for i in range(1, count):
        lines.append(f"    total += {module_name(i)}.run_{i}(total % 1000 + {i})")
    lines += ["    world: Array[Particle] = []", f"    for k in 0..{LIVE_INSTANCES}:", "        world.push(Particle())",
              "    started = Instant.now()", "    last = -1",
              "    while started.elapsed().as_secs_f64() < 600.0:",
              "        for p in world:", "            p.x += p.step",
              f"        value = {module_name(middle)}.work_{middle}(1)",
              "        if value != last:",
              "            println(f\"work {value} live {world.len()}\")",
              "            last = value",
              "        hot.checkpoint()",
              "        sleep(Duration.from_millis(1))",
              "    println(total)"]
    return "\n".join(lines) + "\n"


def header(lines):
    """A C header of Vulkan's size: enums, structs, function pointer types and prototypes."""
    out = ["/* Generated by bench/bigpkg/generate.py: a C header of Vulkan's size. Do not edit. */",
           "#ifndef VKIMPL_H", "#define VKIMPL_H", "#include <stdint.h>", ""]
    group = 0
    while len(out) < lines - 12:
        g = group
        out += [f"typedef enum VkEnum{g} {{"]
        out += [f"    VK_ENUM_{g}_VALUE_{v} = {v}," for v in range(12)]
        out += [f"    VK_ENUM_{g}_MAX = 0x7FFFFFFF", f"}} VkEnum{g};", ""]
        out += [f"typedef struct VkStruct{g} {{", f"    VkEnum{g} kind;", "    const void* next;"]
        out += [f"    uint32_t field{f};" for f in range(6)]
        out += ["    float weights[4];", f"}} VkStruct{g};", ""]
        out += [f"typedef int32_t (*PFN_vkCall{g})(const VkStruct{g}* info, uint32_t count);",
                f"int32_t vkCall{g}(const VkStruct{g}* info, uint32_t count);", ""]
        group += 1
    out += ["int64_t vk_mix(int64_t a, int64_t b);", "", "#endif", ""]
    return "\n".join(out)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = text.encode("utf-8")
    try:
        with open(path, "rb") as existing:
            if existing.read() == data:
                return
    except OSError:
        pass
    with open(path, "wb") as f:
        f.write(data)


def generate(out, modules=400, lines=50000, header_lines=HEADER_LINES, live=False, fanout=None):
    """Write the package into `out` (its manifest, `src/`), returning the module count. `live`: a
    reloadable package whose `main` keeps running (`[HR-1]`, `live_main_module`); `fanout`: `main`
    reaches the modules through a tree of modules calling at most that many each
    (`fanout_modules`)."""
    if modules < 3:
        raise ValueError("bigpkg needs at least 3 modules: m000, one more, and the leaf")
    per_module = max(lines // modules, 30)
    src = os.path.join(out, "src")
    manifest = '[package]\nname = "bigpkg"\nversion = "0.1.0"\n'
    write(os.path.join(out, "ember.toml"), manifest + ('\n[build]\nreload = "all"\n' if live else ""))
    write(os.path.join(src, "m000.em"), core_with_field(0))
    for index in range(1, modules - 1):
        write(os.path.join(src, f"{module_name(index)}.em"), module_text(index, modules, per_module))
    write(os.path.join(src, f"{module_name(modules - 1)}.em"), leaf_module(modules - 1, modules))
    if live:
        write(os.path.join(src, "main.em"), live_main_module(modules))
    elif fanout:
        tree, calls = fanout_modules(modules, fanout)
        for name, text in tree:
            write(os.path.join(src, f"{name}.em"), text)
        write(os.path.join(src, "main.em"), main_module(modules, calls))
    else:
        write(os.path.join(src, "main.em"), main_module(modules))
    write(os.path.join(src, "vkimpl.h"), header(header_lines))
    write(os.path.join(src, "vkimpl.c"), '#include "vkimpl.h"\n\nint64_t vk_mix(int64_t a, int64_t b) { return a * 31 + b; }\n')
    return modules


def edit(out, kind, n, modules=400, lines=50000):
    """`[BUD-2]`'s edits, the `n`th of each kind: `body` changes one function body in the middle
    module, `signature` the leaf's signature (both ways in turn), `type` the widely imported
    `Item` (a defaulted field added, then its default changed, then removed)."""
    src = os.path.join(out, "src")
    per_module = max(lines // modules, 30)
    if kind == "body":
        middle = modules // 2
        write(os.path.join(src, f"{module_name(middle)}.em"), module_text(middle, modules, per_module, body_value=n + 2))
    elif kind == "signature":
        write(os.path.join(src, f"{module_name(modules - 1)}.em"), leaf_module(modules - 1, modules, wide=n % 2 == 0))
    elif kind == "type":
        write(os.path.join(src, "m000.em"), core_with_field(n + 1 if n % 2 == 0 else 0))
    else:
        raise ValueError(f"unknown edit {kind}")


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("out")
    parser.add_argument("--modules", type=int, default=400)
    parser.add_argument("--lines", type=int, default=50000)
    parser.add_argument("--header-lines", type=int, default=HEADER_LINES)
    parser.add_argument("--live", action="store_true")
    parser.add_argument("--fanout", type=int, help="main reaches the modules through a tree of modules calling at most N each")
    args = parser.parse_args(argv)
    generate(args.out, args.modules, args.lines, args.header_lines, args.live, args.fanout)
    count = sum(open(os.path.join(args.out, "src", name), encoding="utf-8").read().count("\n")
                for name in os.listdir(os.path.join(args.out, "src")) if name.endswith(".em"))
    print(f"bigpkg: {args.modules} modules, {count} lines of Ember, in {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
