//! The public C surface of one emitted package (`[FFI-26]`). Names and
//! declarators come from the same emitter and type plan as the C translation
//! unit, while the dependency walk limits this header to exported types.

use super::{Definition, Emitter, HeaderOutput, TypeNode, ALIGNED_MACRO};
use ember_mir::Body;
use ember_types::{Ty, TyKind, IntTy, UintTy};
use std::collections::BTreeSet;

pub(super) fn render(emitter: &Emitter<'_>, bodies: &[Body], package_name: &str) -> Result<HeaderOutput, String> {
    let exports: Vec<&Body> = bodies.iter()
        .filter(|body| body.abi.is_some()
            && !body.is_extern_declaration && !body.is_abstract)
        .collect();
    let mut reachable = Reachable::new(emitter);
    for body in &exports {
        reachable.visit(body.return_ty())?;
        for (_, parameter) in body.args() {
            reachable.visit(parameter.ty)?;
        }
    }
    for table in emitter.types.export_tables() {
        reachable.visit(table.ty)?;
    }

    // Hex of the exact UTF-8 bytes is injective: e.g. foo-bar, foo_bar and
    // differently spelled Unicode names must never suppress each other.
    let mut base_guard = String::from("EMBER_GENERATED_HEADER_");
    for byte in package_name.as_bytes() {
        base_guard.push_str(&format!("{byte:02X}"));
    }
    base_guard.push_str("_H");
    let mut guard = base_guard.clone();
    let mut suffix = 2;
    while exports.iter().any(|body| body.symbol == guard)
        || emitter.order.iter().any(|node| emitter.node_name(*node) == guard)
        || reachable.opaque.contains(&guard) {
        guard = format!("{base_guard}_{suffix}");
        suffix += 1;
    }

    let mut out = String::new();
    line(&mut out, "/* Generated by Ember. C ABI declarations for package exports. */");
    line(&mut out, &format!("#ifndef {guard}"));
    line(&mut out, &format!("#define {guard}"));
    line(&mut out, "#include <stdbool.h>");
    line(&mut out, "#include <stddef.h>");
    line(&mut out, "#include <stdint.h>");
    // `[FFI-31]` — a shared library's host fills an `ember_rt_config` for `ember_module_init`.
    if reachable.runtime_integer_carrier || emitter.module {
        line(&mut out, &format!("#include \"{}_runtime/{}\"",
            ember_branding::SYMBOL_PREFIX, ember_branding::runtime_header()));
    }
    line(&mut out, "");
    // `[FFI-9]` — an export or a function pointer type with another convention names its macro.
    let plan: Vec<_> = emitter.order.iter().copied()
        .filter(|node| reachable.nodes.contains(node))
        .map(|node| (emitter.node_name(node), emitter.definition(node), node))
        .collect();
    if exports.iter().any(|body| !super::calling_convention(body.abi.as_deref()).is_empty())
        || plan.iter().any(|(_, definition, _)| matches!(definition, Definition::FnPointer { convention, .. } if !convention.is_empty()))
    {
        out.push_str(super::CALLING_CONVENTION_MACROS);
        line(&mut out, "");
    }
    line(&mut out, "#ifdef __cplusplus");
    line(&mut out, "extern \"C\" {");
    line(&mut out, "#endif");

    for opaque in &reachable.opaque {
        line(&mut out, &format!("struct {opaque};"));
    }
    // `[BLD-FFI-5a]` (ODR-162) — each `@sync` class an export hands over: its object's struct,
    // which C holds only behind a pointer, under the class's name.
    let classes = super::class_exports::plan(emitter, bodies, package_name);
    for class in &classes {
        line(&mut out, &format!("typedef struct {} {};", emitter.object_struct(class.class), class.name));
    }
    if plan.iter().any(|(_, _, node)| emitter.node_layout_attrs(*node).align > 1) {
        out.push_str(ALIGNED_MACRO);
    }
    if !plan.is_empty() {
        line(&mut out, "");
        for (name, definition, _) in &plan {
            if matches!(definition, Definition::Struct(_)) {
                line(&mut out, &format!("typedef struct {name} {name};"));
            }
        }
        for (name, definition, node) in &plan {
            match definition {
                Definition::Alias(underlying) => line(&mut out, &format!("typedef {underlying} {name};")),
                Definition::FnPointer { ret, convention, args } =>
                    line(&mut out, &format!("typedef {ret} ({convention}*{name})({args});")),
                // `[LAY-2]` — the layout check in C++'s spelling too, for a C++ host.
                Definition::Struct(members) => {
                    for text in emitter.struct_definition(name, members, *node) {
                        match text.strip_prefix("_Static_assert(") {
                            Some(check) => {
                                line(&mut out, "#ifdef __cplusplus");
                                line(&mut out, &format!("static_assert({}", check.replace("_Alignof(", "alignof(")));
                                line(&mut out, "#else");
                                line(&mut out, &text);
                                line(&mut out, "#endif");
                            }
                            None => line(&mut out, &text),
                        }
                    }
                }
            }
        }
    }
    if !exports.is_empty() { line(&mut out, ""); }
    for body in exports {
        line(&mut out, &format!("/* threads: {} */", body.export_thread_policy.as_str()));
        match ember_branding::export_alias_symbol(&body.symbol) {
            // `[MNG-2]` — its symbol, which C cannot spell, under its C name.
            Some(exact) => {
                line(&mut out, &format!("/* symbol: {exact} */"));
                line(&mut out, &super::exact_symbol_prototype(&emitter.signature(body), &body.symbol, &exact));
            }
            // `[BLD-FFI-5a]` — a class's handle by the class's name.
            None => {
                let mut signature = emitter.signature(body);
                for class in &classes {
                    signature = signature.replace(&format!("struct {}*", emitter.object_struct(class.class)), &format!("{}*", class.name));
                }
                line(&mut out, &format!("{signature};"));
            }
        }
    }
    // `[BLD-FFI-5a]` — a class's handle: a count taken and given back (the last one's end frees
    // the object), and each `pub` method, its object first.
    for class in &classes {
        line(&mut out, "");
        line(&mut out, &format!("/* `{0}`, an Ember `@sync` class: each handle holds a count of the object (atomic, so on", class.name));
        line(&mut out, " * any thread); retain takes another, release gives one back, and the last one's release frees it. */");
        line(&mut out, &format!("void {}({}* self);", class.retain, class.name));
        line(&mut out, &format!("void {}({}* self);", class.release, class.name));
        for method in &class.methods {
            line(&mut out, &format!("{} {}({});", method.ret, method.symbol, method.params.join(", ")));
        }
        for (method, why) in &class.skipped {
            line(&mut out, &format!("/* not for C: `{}.{method}`: {why} */", class.name));
        }
    }
    // `[FFI-26]` — each export table, its protocol version, and each entry's thread contract.
    for table in emitter.types.export_tables() {
        let TyKind::Struct(id) = emitter.types.kind(table.ty) else { continue };
        let fields = emitter.types.struct_def(*id).fields.iter().map(|field| field.name).collect::<Vec<_>>();
        line(&mut out, "");
        line(&mut out, &format!("/* export table `{}`, protocol {}; each entry's threads: */", table.name, table.protocol));
        for (field, symbol) in fields.iter().zip(&table.entries) {
            let policy = bodies.iter().find(|body| &body.symbol == symbol)
                .map_or("any", |body| body.export_thread_policy.as_str());
            line(&mut out, &format!("/*   {field}: {policy} */"));
        }
        line(&mut out, &format!("#define {}_PROTOCOL {}u", table.name, table.protocol));
        line(&mut out, &format!("extern const {} {};", emitter.c_type(table.ty), table.symbol()));
    }
    if emitter.module {
        let rt = ember_branding::runtime("");
        line(&mut out, "");
        line(&mut out, "/* [FFI-31], [ABI-1] Look this up before calling into the library: a library built for");
        line(&mut out, " * other start-up rules does not have it. */");
        line(&mut out, &format!("extern const uint32_t {rt}module_protocol_v1;"));
        line(&mut out, "/* [FFI-31] Call before using this library, on the thread that becomes its creator; returns 0,");
        line(&mut out, " * or EMBER_MODULE_INIT_ABI_MISMATCH for a runtime of another ABI version ([ABI-3]). */");
        line(&mut out, &format!("int {rt}module_init(const {rt}rt_config* cfg);"));
        line(&mut out, "/* [FFI-31] Call before unloading this library: runs the runtime's shutdown when it is its");
        line(&mut out, " * last module (at-exit hooks, the debug leak report, every thread detached). */");
        line(&mut out, &format!("void {rt}module_shutdown(void);"));
    }
    line(&mut out, "");
    line(&mut out, "#ifdef __cplusplus");
    line(&mut out, "}");
    line(&mut out, "#endif");
    line(&mut out, &format!("#endif /* {guard} */"));
    let cpp_source = render_cpp(emitter, bodies, package_name);
    Ok(HeaderOutput { source: out, needs_runtime_header: reachable.runtime_integer_carrier || emitter.module, cpp_source })
}

/// `[BLD-FFI-5]` — the C++ header `ember build --emit header --cpp` writes beside the C one: the C
/// header, and in a namespace named for the package, each export, as an inline function that takes
/// a `std::string_view` (for bytes) or a `std::span` where the C function takes a pointer and a
/// length (a `*T` or `*mut T` and the `usize` after it) and calls the C function with their
/// `data()` and `size()`; any other export, by `using`. A span needs C++20 (`__cpp_lib_span`): an
/// export taking one is declared only where the library has it.
fn render_cpp(emitter: &Emitter<'_>, bodies: &[Body], package_name: &str) -> String {
    let namespace: String = package_name.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect();
    let namespace = if namespace.starts_with(|c: char| c.is_ascii_digit()) { format!("_{namespace}") } else { namespace };
    let mut out = String::new();
    line(&mut out, "/* Generated by Ember. C++ declarations for package exports ([BLD-FFI-5]). */");
    line(&mut out, "#pragma once");
    line(&mut out, &format!("#include \"{package_name}.h\""));
    line(&mut out, "#include <cstddef>");
    line(&mut out, "#include <cstdint>");
    line(&mut out, "#include <string_view>");
    line(&mut out, "#if __has_include(<version>)");
    line(&mut out, "#include <version>");
    line(&mut out, "#endif");
    line(&mut out, "#if defined(__cpp_lib_span)");
    line(&mut out, "#include <span>");
    line(&mut out, "#endif");
    line(&mut out, "#include <utility>");
    line(&mut out, "");
    line(&mut out, &format!("namespace {namespace} {{"));
    // `[BLD-FFI-5a]` (ODR-162) — each `@sync` class an export hands over, as a class of its name:
    // a copyable handle whose copies share the object (its counts are atomic) and whose last end
    // frees it, with the class's `pub` methods.
    let classes = super::class_exports::plan(emitter, bodies, package_name);
    for class in &classes {
        line(&mut out, &format!("class {};", class.name));
    }
    for class in &classes {
        let name = &class.name;
        line(&mut out, &format!("/* [BLD-FFI-5a] `{name}`, an Ember `@sync` class: copies share the object; the last one's end frees it. */"));
        line(&mut out, &format!("class {name} {{"));
        line(&mut out, "public:");
        line(&mut out, &format!("    explicit {name}(::{name}* handle) noexcept : handle_(handle) {{}}"));
        line(&mut out, &format!("    {name}(const {name}& other) noexcept : handle_(other.handle_) {{ if (handle_) ::{}(handle_); }}", class.retain));
        line(&mut out, &format!("    {name}({name}&& other) noexcept : handle_(other.handle_) {{ other.handle_ = nullptr; }}"));
        line(&mut out, &format!("    {name}& operator=(const {name}& other) noexcept {{ {name} copy(other); std::swap(handle_, copy.handle_); return *this; }}"));
        line(&mut out, &format!("    {name}& operator=({name}&& other) noexcept {{ std::swap(handle_, other.handle_); return *this; }}"));
        line(&mut out, &format!("    ~{name}() {{ if (handle_) ::{}(handle_); }}", class.release));
        line(&mut out, &format!("    ::{name}* get() const noexcept {{ return handle_; }}"));
        for method in &class.methods {
            let params: Vec<&str> = method.cpp_params.iter().map(|(declared, _)| declared.as_str()).collect();
            let ret = method.cpp_class_result.clone().unwrap_or_else(|| method.ret.clone());
            line(&mut out, &format!("    {ret} {}({}) const;", method.name, params.join(", ")));
        }
        line(&mut out, "private:");
        line(&mut out, &format!("    ::{name}* handle_;"));
        line(&mut out, "};");
    }
    for class in &classes {
        for method in &class.methods {
            let params: Vec<&str> = method.cpp_params.iter().map(|(declared, _)| declared.as_str()).collect();
            let passed: Vec<&str> = std::iter::once("handle_").chain(method.cpp_params.iter().map(|(_, passed)| passed.as_str())).collect();
            let call = format!("::{}({})", method.symbol, passed.join(", "));
            let (ret, body) = match &method.cpp_class_result {
                Some(other) => (other.clone(), format!("return {other}({call});")),
                None if method.ret == "void" => (method.ret.clone(), format!("{call};")),
                None => (method.ret.clone(), format!("return {call};")),
            };
            let span = method.cpp_params.iter().any(|(declared, _)| declared.starts_with("std::span"));
            if span {
                line(&mut out, "#if defined(__cpp_lib_span)");
            }
            line(&mut out, &format!("inline {ret} {}::{}({}) const {{ {body} }}", class.name, method.name, params.join(", ")));
            if span {
                line(&mut out, "#endif");
            }
        }
    }
    for body in bodies.iter().filter(|body| body.abi.is_some() && !body.is_extern_declaration && !body.is_abstract) {
        // A C name C++ can call as written, with the plain C signature.
        let plain = ember_branding::export_alias_symbol(&body.symbol).is_none()
            && super::calling_convention(body.abi.as_deref()).is_empty()
            && !body.restrict_views
            && !emitter.split_views.contains_key(&body.symbol)
            && !emitter.ffi_export_value_params.contains_key(&body.symbol);
        if !plain {
            continue;
        }
        let args: Vec<(String, ember_types::Ty)> = body
            .args()
            .enumerate()
            .map(|(index, (_, decl))| (decl.name.clone().filter(|name| name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')).unwrap_or_else(|| format!("_{index}")), decl.ty))
            .collect();
        // `[BLD-FFI-5a]` — an export that takes or gives a class's object: in C++, the class.
        let class_of = |ty: ember_types::Ty| match emitter.types.kind(ty) {
            TyKind::Class(id) => classes.iter().find(|class| class.class == *id).map(|class| class.name.clone()),
            _ => None,
        };
        if args.iter().any(|(_, ty)| class_of(*ty).is_some()) || class_of(body.return_ty()).is_some() {
            let params: Vec<String> = args.iter().map(|(name, ty)| match class_of(*ty) {
                Some(class) => format!("const {class}& {name}"),
                None => format!("{} {name}", emitter.c_member_type(*ty)),
            }).collect();
            let passed: Vec<String> = args.iter().map(|(name, ty)| if class_of(*ty).is_some() { format!("{name}.get()") } else { name.clone() }).collect();
            let call = format!("::{}({})", body.symbol, passed.join(", "));
            let short = body.symbol.rsplit("__").next().unwrap_or(&body.symbol);
            let (ret, made) = match class_of(body.return_ty()) {
                Some(class) => (class.clone(), format!("return {class}({call});")),
                None => {
                    let ret = emitter.c_type(body.return_ty());
                    let made = if ret == "void" { format!("{call};") } else { format!("return {call};") };
                    (ret, made)
                }
            };
            line(&mut out, &format!("/* threads: {} */", body.export_thread_policy.as_str()));
            line(&mut out, &format!("inline {ret} {short}({}) {{ {made} }}", params.join(", ")));
            continue;
        }
        let mut params = Vec::new();
        let mut passed = Vec::new();
        let mut span = false;
        let mut index = 0;
        while index < args.len() {
            let (name, ty) = &args[index];
            let length = args.get(index + 1).filter(|(_, next)| matches!(emitter.types.kind(*next), TyKind::Uint(UintTy::Usize)));
            match (emitter.types.kind(*ty), length) {
                (TyKind::Ptr { mutable, inner }, Some(_)) => {
                    let element = emitter.c_type(*inner);
                    let bytes = matches!(emitter.types.kind(*inner), TyKind::Uint(UintTy::U8) | TyKind::Int(IntTy::I8));
                    if bytes && !mutable {
                        params.push(format!("std::string_view {name}"));
                        passed.push(format!("reinterpret_cast<const {element}*>({name}.data())"));
                    } else {
                        span = true;
                        params.push(format!("std::span<{}{element}> {name}", if *mutable { "" } else { "const " }));
                        passed.push(format!("{name}.data()"));
                    }
                    passed.push(format!("{name}.size()"));
                    index += 2;
                }
                _ => {
                    params.push(format!("{} {name}", emitter.c_member_type(*ty)));
                    passed.push(name.clone());
                    index += 1;
                }
            }
        }
        line(&mut out, &format!("/* threads: {} */", body.export_thread_policy.as_str()));
        line(&mut out, &format!("using ::{};", body.symbol));
        if params.len() == args.len() {
            continue;
        }
        let ret = emitter.c_type(body.return_ty());
        let call = format!("::{}({})", body.symbol, passed.join(", "));
        let short = body.symbol.rsplit("__").next().unwrap_or(&body.symbol);
        if span {
            line(&mut out, "#if defined(__cpp_lib_span)");
        }
        line(&mut out, &format!("inline {ret} {short}({}) {{ {}{call}; }}", params.join(", "), if ret == "void" { "" } else { "return " }));
        if span {
            line(&mut out, "#endif");
        }
    }
    line(&mut out, &format!("}} // namespace {namespace}"));
    out
}

fn line(out: &mut String, value: &str) {
    out.push_str(value);
    out.push('\n');
}

struct Reachable<'a, 'b> {
    emitter: &'a Emitter<'b>,
    seen: BTreeSet<Ty>,
    nodes: BTreeSet<TypeNode>,
    opaque: BTreeSet<String>,
    runtime_integer_carrier: bool,
}

impl<'a, 'b> Reachable<'a, 'b> {
    fn new(emitter: &'a Emitter<'b>) -> Self {
        Self { emitter, seen: BTreeSet::new(), nodes: BTreeSet::new(),
            opaque: BTreeSet::new(), runtime_integer_carrier: false }
    }

    fn visit(&mut self, ty: Ty) -> Result<(), String> {
        if !self.seen.insert(ty) { return Ok(()); }
        match self.emitter.types.kind(ty).clone() {
            TyKind::Int(IntTy::I128 | IntTy::I256) | TyKind::Uint(UintTy::U128 | UintTy::U256) => {
                self.runtime_integer_carrier = true;
            }
            TyKind::Struct(id) => {
                if !self.emitter.types.is_ffi_safe(ty) || self.emitter.types.needs_drop(ty) {
                    return Err(self.unsupported(ty));
                }
                self.nodes.insert(TypeNode::Struct(id));
                let fields = self.emitter.types.struct_def(id).fields.iter().map(|field| field.ty).collect::<Vec<_>>();
                for field in fields { self.visit(field)?; }
            }
            TyKind::Enum(id) => {
                if !self.emitter.types.is_ffi_safe(ty) { return Err(self.unsupported(ty)); }
                self.nodes.insert(TypeNode::Enum(id));
                let def = self.emitter.types.enum_def(id);
                let repr = def.repr;
                let fields = def.variants.iter().flat_map(|variant|
                    variant.fields.iter().map(|field| field.ty)).collect::<Vec<_>>();
                self.visit(repr)?;
                for field in fields { self.visit(field)?; }
            }
            TyKind::Fn { params, ret, abi, .. } => {
                if abi.is_none() {
                    return Err(self.unsupported(ty));
                }
                self.nodes.insert(TypeNode::Structural(ty));
                for param in params { self.visit(param.ty)?; }
                self.visit(ret)?;
            }
            TyKind::Array { elem, .. } => {
                self.nodes.insert(TypeNode::Structural(ty));
                self.visit(elem)?;
            }
            TyKind::Ptr { inner, .. } | TyKind::Ref { inner, .. } => self.visit(inner)?,
            TyKind::Opaque(name) => {
                self.opaque.insert(name.as_str().rsplit('.').next().unwrap_or(name.as_str()).to_string());
            }
            TyKind::Bool | TyKind::Char | TyKind::Int(_) | TyKind::Uint(_)
            | TyKind::Float(_) | TyKind::CLongDouble | TyKind::Void | TyKind::Never | TyKind::CStr => {}
            // `[FFI-8]` — the runtime header's `ember_va_list`.
            TyKind::VaList => self.runtime_integer_carrier = true,
            // `[BLD-FFI-5a]` — a `@sync` class's handle, declared with its methods.
            TyKind::Class(id) if self.emitter.types.class_def(id).is_sync => {}
            _ => return Err(self.unsupported(ty)),
        }
        Ok(())
    }

    fn unsupported(&self, ty: Ty) -> String {
        format!("cannot emit C export header: reachable type `{}` has no supported public C declaration",
            self.emitter.types.symbol_name(ty))
    }
}
